export class CalculateService {
    plus(a : number, b : number) : number {
        return (a + b);
    }
    minus(a : number, b : number) : number {
        return (a - b);
    }
    multi(a : number, b : number) : number {
        return (a * b);
    }
    divide(a : number, b : number) : number {
        return (a / b);
    }
}